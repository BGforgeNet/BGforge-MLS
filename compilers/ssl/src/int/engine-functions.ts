/** Fallout 1 spellings for the reused opcode slots, resolved through the one ordered table. */
const FALLOUT1_ONLY: Readonly<Record<string, string>> = {
    animate_jump: "ANIMATE_JUMP",
    barter_asking: "BARTER_ASKING",
    barter_offer: "BARTER_OFFER",
    reaction: "REACTION",
    town_map: "TOWN_MAP",
    turn_off_objs_in_area: "TURN_OFF_OBJS_IN_AREA",
    turn_on_objs_in_area: "TURN_ON_OBJS_IN_AREA",
};

/** Looks up an engine function by its source spelling for the target game. */
export function engineFunction(name: string, game: 1 | 2 = 2): EngineFunction | undefined {
    if (game === 1) {
        const opcodeName = FALLOUT1_ONLY[name];
        const opcode = opcodeName === undefined ? undefined : FALLOUT1_OPCODES[opcodeName];
        if (opcode !== undefined) return { opcode };
    }
    return ENGINE_FUNCTIONS[name];
}

/** Named engine function per opcode, built once from the forward table so the two cannot disagree. */
const BY_OPCODE = new Map<number, { name: string } & EngineFunction>(
    Object.entries(ENGINE_FUNCTIONS).map(([name, entry]) => [entry.opcode, { name, ...entry }]),
);

/**
 * The engine function an opcode dispatches to, for decompiling.
 *
 * Fallout 1 spellings are deliberately not resolved here. They share opcode numbers with the Fallout 2
 * names, so a reverse lookup cannot tell the two apart from the number alone - the caller knows which
 * game a file targets, and picking one silently would put the wrong name in decompiled output.
 */
export function engineFunctionAt(opcode: number): ({ name: string } & EngineFunction) | undefined {
    return BY_OPCODE.get(opcode);
}
