/**
 * Engine function names as written in source, mapped to the opcode they compile to.
 *
 * A call like `display_msg("x")` is not a procedure call: it pushes its arguments and then a single
 * opcode the engine dispatches on. This table is what turns the source spelling into that number, so
 * the front end needs no knowledge of the opcode layout.
 *
 * `popsResult` marks the 27 functions that return a value even when called as a statement; their
 * statement form drops the result rather than leaving it on the stack.
 *
 * Fallout 1 reuses 7 opcode numbers for different functions under different source names (see
 * `opcodes-engine.ts`). Those names are listed separately so that compiling for Fallout 2 does not
 * silently accept a Fallout 1 spelling and emit the wrong function.
 */

import { EngineOp, FALLOUT1_OPCODES, LibOp } from "./opcodes-engine";

export interface EngineFunction {
    opcode: number;
    /**
     * How many stack values the opcode consumes. The compiler does not need this - the source supplies
     * the arguments - but the decompiler cannot recover a call without it, since an opcode alone says
     * nothing about its operand count. Absent for the four functions the signature data does not
     * describe, which the decompiler reports rather than guessing at.
     *
     * Maintained by `scripts/utils/src/update-ssl-engine-arity.ts`; edit the signatures in
     * `server/data/fallout-ssl-*.yml` and re-run it rather than editing these numbers.
     */
    args?: number;
    /**
     * The opcode leaves a value on the stack. Distinct from `popsResult`, which records what the
     * reference emits in statement position and is verified against its output; this records what the
     * documented signature says the call yields, and the decompiler needs it to know whether an opcode
     * contributes an operand to the enclosing expression.
     */
    returns?: boolean;
    /** The statement form discards a returned value. */
    popsResult?: boolean;
    /**
     * Bitmask of argument positions that take a PROCEDURE rather than a value: bit N marks argument N.
     * A procedure named in such a position is passed by reference; naming it anywhere else calls it.
     */
    procArgs?: number;
}

