/**
 * Library and engine opcode tables.
 *
 * The interpreter's opcode space is one contiguous run: the 76 core instructions in `opcodes.ts`,
 * then 85 library opcodes, then 481 engine ("extended") opcodes. Only the core set is instruction
 * semantics; everything here is a named engine function dispatched by number, so a call site pushes its
 * arguments in order and then the opcode.
 *
 * As with the core table, order is the contract and the numbers are derived from position - the numbering
 * is frozen because changing it would invalidate every compiled script in existence.
 *
 * Fallout 1 and Fallout 2 share the numbering exactly: the two builds differ at only 7 positions, and at
 * each of those the slot holds a DIFFERENT FUNCTION under the same number rather than shifting anything
 * after it. So one table plus a small per-position override is the whole difference, and an opcode number
 * decoded without knowing the target game is still unambiguous as a number - just not as a name.
 */

