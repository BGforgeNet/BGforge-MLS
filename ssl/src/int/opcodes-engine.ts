/**
 * Positions where Fallout 1 gives the same opcode number a different function. Keyed by index into
 * ENGINE_OPCODES rather than by opcode value, so the two stay in step if the base ever moves.
 */
const FALLOUT1_OVERRIDES: Readonly<Record<number, string>> = {
    17: "REACTION", // Fallout 2: MARK_AREA_KNOWN
    46: "ANIMATE_JUMP", // Fallout 2: TILE_IN_TILE_RECT
    64: "TURN_OFF_OBJS_IN_AREA", // Fallout 2: METARULE3
    65: "TURN_ON_OBJS_IN_AREA", // Fallout 2: SET_MAP_MUSIC
    68: "BARTER_OFFER", // Fallout 2: WM_AREA_SET_POS
    69: "BARTER_ASKING", // Fallout 2: SET_EXIT_GRIDS
    104: "TOWN_MAP", // Fallout 2: INVEN_CMDS
};

export type LibOpcodeName = (typeof LIB_OPCODES)[number];
export type EngineOpcodeName = (typeof ENGINE_OPCODES)[number];

const LIB_BASE = O_OPERATOR + CORE_COUNT;
const ENGINE_BASE = LIB_BASE + LIB_OPCODES.length;

function tableOf(names: readonly string[], base: number): Readonly<Record<string, number>> {
    const table: Record<string, number> = {};
    names.forEach((name, index) => {
        table[name] = base + index;
    });
    return table;
}

/** Library opcodes by name, e.g. `LibOp.SAYSTART`. */
export const LibOp = tableOf(LIB_OPCODES, LIB_BASE) as Readonly<Record<LibOpcodeName, number>>;

/** Engine opcodes by name, e.g. `EngineOp.GIVE_EXP_POINTS`. */
export const EngineOp = tableOf(ENGINE_OPCODES, ENGINE_BASE) as Readonly<Record<EngineOpcodeName, number>>;

/** Opcode number one past the last engine opcode, for range checks. */
export const OPCODE_LIMIT = ENGINE_BASE + ENGINE_OPCODES.length;

/**
 * Name for an opcode value, given the target game. Returns undefined for the core range, which
 * `opcodeName` in `opcodes.ts` covers.
 */
export function engineOpcodeName(value: number, game: 1 | 2 = 2): string | undefined {
    if (value >= LIB_BASE && value < ENGINE_BASE) return LIB_OPCODES[value - LIB_BASE];
    if (value >= ENGINE_BASE && value < OPCODE_LIMIT) {
        const index = value - ENGINE_BASE;
        return (game === 1 ? FALLOUT1_OVERRIDES[index] : undefined) ?? ENGINE_OPCODES[index];
    }
    return undefined;
}
